def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        reference = node["$ref"]
        assert isinstance(reference, str)
        return reference.split("/")[-1]
    if "anyOf" in node:
        return " | ".join(ts_type(part) for part in node["anyOf"])
    if "enum" in node:
        return " | ".join(json.dumps(value) for value in node["enum"])
    if "const" in node:
        return json.dumps(node["const"])
    kind = node.get("type")
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(item) for item in node["prefixItems"]) + "]"
        return "Array<" + ts_type(node.get("items", {})) + ">"
    if kind == "object":
        if "additionalProperties" in node and isinstance(node["additionalProperties"], dict):
            return "Record<string, " + ts_type(node["additionalProperties"]) + ">"
        return "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind if isinstance(kind, str) else "", "unknown")


def typescript(schema: dict[str, Any]) -> str:
    lines = ["// Generated by python -m harness_schema.generate. Do not edit.\n"]
    for name, definition in {**schema.get("$defs", {}), "Run": schema}.items():
        lines.append(f"export interface {name} {{")
        for key, prop in definition.get("properties", {}).items():
            lines.append(f"  {key}: {ts_type(prop)};")
        lines.append("}\n")
    return "\n".join(lines)


def reading(label: str, gloss: str, op: str) -> Reading:
    prefix = "PREFIX hrn: <https://harness.local/schema#>\n"
    match op:
        case "citation count":
            classes = ["Author", "Paper", "Citation"]
            axioms = [
                ("author_of", "Paper", "Author"),
                ("cites", "Paper", "Paper"),
                ("citation_count", "Author", "xsd:integer"),
            ]
            query = "SELECT ?author (COUNT(?citing) AS ?n) WHERE { ?paper hrn:author_of ?author . ?citing hrn:cites ?paper . } GROUP BY ?author ORDER BY DESC(?n) LIMIT 10"
            answer = "Under this reading, Jonathan Berant ranks first with 214 in-corpus citations, ahead of Matt Gardner (187)."
            rows = [
                ("Jonathan Berant", "in_corpus_citations", "214"),
                ("Matt Gardner", "in_corpus_citations", "187"),
            ]
            precision, recall = (2, 3), (2, 2)
        case "first-author count":
            classes = ["Author", "Paper"]
            axioms = [("first_author_of", "Paper", "Author"), ("year", "Paper", "xsd:gYear")]
            query = "SELECT ?author (COUNT(?paper) AS ?n) WHERE { ?paper hrn:first_author_of ?author ; hrn:year ?year . } GROUP BY ?author ORDER BY DESC(?n)"
            answer = "Under this reading, Tomer Wolfson ranks first with 3 first-author papers, ahead of Mor Geva (2)."
            rows = [
                ("Tomer Wolfson", "first_author_papers", "3"),
                ("Mor Geva", "first_author_papers", "2"),
            ]
            precision, recall = (2, 2), (2, 3)
        case "venue rank":
            classes = ["Author", "Paper", "Venue"]
            axioms = [
                ("author_of", "Paper", "Author"),
                ("published_in", "Paper", "Venue"),
                ("venue_rank", "Venue", "xsd:decimal"),
            ]
            query = "SELECT ?author (SUM(?rank) AS ?score) WHERE { ?paper hrn:author_of ?author ; hrn:published_in ?venue . ?venue hrn:venue_rank ?rank . } GROUP BY ?author ORDER BY DESC(?score)"
            answer = "Under this reading, Jonathan Berant and Matt Gardner tie at a venue-weighted score of 24."
            rows = [
                ("Jonathan Berant", "venue_weighted_score", "24"),
                ("Matt Gardner", "venue_weighted_score", "24"),
            ]
            precision, recall = (2, 2), (2, 4)
        case "co-author count":
            classes = ["Author", "Paper"]
            axioms = [("author_of", "Paper", "Author"), ("co_author_with", "Author", "Author")]
            query = "SELECT ?author (COUNT(DISTINCT ?peer) AS ?n) WHERE { ?paper hrn:author_of ?author, ?peer . FILTER (?peer != ?author) } GROUP BY ?author ORDER BY DESC(?n)"
            answer = "Under this reading, Matt Gardner ranks first with 19 distinct co-authors, ahead of Jonathan Berant (17)."
            rows = [
                ("Matt Gardner", "distinct_co_authors", "19"),
                ("Jonathan Berant", "distinct_co_authors", "17"),
            ]
            precision, recall = (2, 2), (2, 5)
        case _:
            raise ValueError(f"unknown fixture reading: {op}")
    triples = [
        Triple(
            s=subject,
            p=property_name,
            o=value,
            support="Fixture support",
            evidence="Illustrative fixture evidence; live provenance begins in M2.",
            source="Fixture · aggregation",
            tripleId=f"t-{index:03d}",
        )
        for index, (subject, property_name, value) in enumerate(rows, 1)
    ]
    measure = rows[0][1].replace("_", " ")
    return Reading(
        label=label,
        gloss=gloss,
        op=op,
        classes=classes,
        properties=[axiom[0] for axiom in axioms],
        axioms=axioms,
        sparql=prefix + query,
        answer=answer,
        triples=triples,
        metrics=Metrics(disagreement=None, precision=precision, recall=recall),
        status="answered",
        measure=measure,
        graph=fixture_graph(rows, measure),
        schemaTerms=fixture_terms(classes, axioms),
    )


def fixture_terms(classes: list[str], axioms: list[tuple[str, str, str]]) -> list[SchemaTerm]:
    """Illustrative subschema terms with origins (Phase 4): DBLP, harness core and invented."""
    hrn, dblp = "https://harness.local/schema#", "https://dblp.org/rdf/schema#"
    terms = [
        SchemaTerm(name=f"hrn:{name}", iri=f"{hrn}{name}", kind="class",
                   origin="core" if name in {"Author", "Paper", "Venue"} else "invented",
                   parent=None if name in {"Author", "Paper", "Venue"} else "hrn:ResearchEntity",
                   definition=None if name in {"Author", "Paper", "Venue"} else f"Run-local class {name} (fixture).")
        for name in classes
    ]
    for name, domain, range_ in axioms:
        literal = range_.startswith("xsd:")
        if name == "cites":
            terms.append(SchemaTerm(name="hrn:cites", iri=f"{hrn}cites", kind="object", origin="core",
                                    domain="hrn:Paper", range="hrn:Paper"))
        elif name == "year":
            terms.append(SchemaTerm(name="dblp:yearOfPublication", iri=f"{dblp}yearOfPublication", kind="datatype",
                                    origin="dblp", domain="dblp:Publication", range="xsd:gYear"))
        else:
            terms.append(SchemaTerm(
                name=f"hrn:{name}", iri=f"{hrn}{name}", kind="datatype" if literal else "object", origin="invented",
                parent="hrn:researchAttribute" if literal else "hrn:researchRelation",
                domain=f"hrn:{domain}", range=range_ if literal else f"hrn:{range_}",
                definition=f"Run-local relation {name} (fixture)."))
    terms.append(SchemaTerm(name="dblp:authoredBy", iri=f"{dblp}authoredBy", kind="object", origin="dblp",
                            parent="dblp:createdBy", domain="dblp:Publication", range="dblp:Creator"))
    return terms


def fixture_graph(rows: list[tuple[str, str, str]], measure: str) -> AnswerGraph:
    """An illustrative connected graph: each ranked author shares one node across their papers,
    and the ranking number is a computed node derived from those author edges."""
    nodes: list[GraphNode] = []
    edges: list[GraphEdge] = []
    computed: list[ComputedResult] = []
    for index, (author, _property, value) in enumerate(rows):
        author_id = f"author:{author.lower().replace(' ', '-')}"
        nodes.append(GraphNode(id=author_id, label=author, kind="author", iri=None))
        derived = []
        for k in range(2):
            paper = f"paper:https://harness.local/resource/p{index * 2 + k + 1}"
            nodes.append(GraphNode(id=paper, label=f"Fixture paper {index * 2 + k + 1}", kind="paper",
                                   iri=paper.split(":", 1)[1]))
            edge_id = f"t-{index:02d}{k}"
            edges.append(GraphEdge(id=edge_id, source=paper, target=author_id, label="authoredBy", kind="fact",
                                   sourceIds=[f"p{index * 2 + k + 1}-metadata"],
                                   evidence="DBLP author list (fixture)", origin="dblp"))
            derived.append(edge_id)
        computed_id = f"computed:{index}"
        label = f"{value} {measure}"
        nodes.append(GraphNode(id=computed_id, label=label, kind="computed", iri=None))
        edges.append(GraphEdge(id=f"d-{index}", source=computed_id, target=author_id, label="computed for",
                               kind="derived", sourceIds=[], evidence=f"count {measure} (fixture)"))
        computed.append(ComputedResult(id=computed_id, label=label, operation=f"count {measure}",
                                       about=author_id, derivedFrom=derived))
    return AnswerGraph(nodes=nodes, edges=edges, computed=computed)


