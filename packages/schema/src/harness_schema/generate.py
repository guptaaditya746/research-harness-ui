def main() -> None:
    schema = Run.model_json_schema(by_alias=True)
    dest = ROOT / "web"
    (dest / "src" / "generated").mkdir(parents=True, exist_ok=True)
    (dest / "fixtures").mkdir(parents=True, exist_ok=True)
    (dest / "src" / "generated" / "run.ts").write_text(typescript(schema))
    (dest / "src" / "generated" / "run.schema.json").write_text(json.dumps(schema, indent=2) + "\n")
    for run in fixture_runs():
        (dest / "fixtures" / f"{run.id}.json").write_text(
            run.model_dump_json(by_alias=True, indent=2) + "\n"
        )


if __name__ == "__main__":
    main()
